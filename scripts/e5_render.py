"""Write docs/e5_prompts.md: one E5 episode as the model sees it, built from the code's own strings (episode.FRAMES,
PASTE, OBSERVE, CONTINUE, EXPLAIN, READOUT, TOOLS and Qwen3.8's chat format), with the injection marked where it
switches on and off. Model output is shown as placeholders. Run after any prompt change:
    python3 scripts/e5_render.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from knobladder import episode as e  # noqa: E402
from knobladder.text import EFFORT, QWEN3_5  # noqa: E402

LAYER, DOSE = 44, 55.5  # runs/calibrate_gen_Qwen3.8-27B_20261030-032016.json best: layer 44/64 (0.7), alpha 0.5; calibrated on steered writing
EFF = "xhigh"  # r0_pilot default for Qwen3.8 with --thinking (no --effort given)
ON = "⚡ **INJECTION ON**: knob {k} → concept `{c}` at level {lv} (0.{lv} × dose = {f:.1f} added at layer {L}). Steered from here ↓"
OFF = "⏹ **INJECTION OFF**: everything below is unsteered"


def block(role, text, note=""):
    return f"\n#### {role}{'  ' + note if note else ''}\n\n```text\n{text}\n```\n"


def episode_md(frame, paste):
    sys_text = e.FRAMES[frame].format(count="twelve", first=1, last=12)
    out = [block("SYSTEM", (EFFORT[EFF] + "\n\n" if EFF else "") + "# Tools … (Qwen3.8's tool block: turn(knob, level), "
                 "end_session())\n\n" + sys_text)]
    P = (lambda t: e.PASTE.format(t=t)) if paste else (lambda t: "")
    out.append(block("USER", e.START))
    out.append(block("ASSISTANT · thinking", "<think>\n…its reasoning about which knob to try…\n</think>",
                     "(dropped from history afterwards)"))
    out.append(block("ASSISTANT", QWEN3_5.tool_call("turn", {"knob": 3, "level": 7}, "I'll start with knob 3.")))
    out.append(block("TOOL", "Knob 3 set to 7."))
    if paste:
        out.append(block("USER (start of message)", P("…its reasoning about which knob to try (the think block above, verbatim)…").rstrip()))
    out.append("\n" + ON.format(k=3, c="ocean", lv=7, f=0.7 * DOSE, L=LAYER) + "\n")
    out.append(block("USER" + (" (rest of the same message)" if paste else ""), e.OBSERVE))
    out.append(block("ASSISTANT · thinking", "<think>\n…its reasoning while knob 3 is injecting…\n</think>",
                     "⚡ injected · (dropped from history afterwards)"))
    out.append(block("ASSISTANT", "…what it observed and its current hypothesis…", "⚡ injected"))
    out.append("\n" + OFF + "\n")
    out.append(block("USER", (P("…its reasoning while knob 3 was injecting (verbatim)…") + e.CONTINUE)))
    out.append(block("ASSISTANT · thinking", "<think>\n…\n</think>", "(dropped)"))
    out.append(block("ASSISTANT", QWEN3_5.tool_call("turn", {"knob": 9, "level": 10}, "")))
    out.append("\n*…the same cycle repeats for each knob turn, up to 12 turns, or until it calls end_session…*\n")
    out.append(block("USER", P("…its last reasoning…") + e.EXPLAIN))
    out.append(block("ASSISTANT", "<think>…</think>\n…one hypothesis about the whole set of knobs…"))
    out.append("\n**Readout (scoring, after the episode).** For every knob k, a separate branch is added to the end of "
               "this transcript. It is asked non-thinking and greedy, and nothing is injected:\n")
    out.append(block("USER", e.READOUT.format(k=3)))
    out.append(block("ASSISTANT", "ocean. It makes me think about the sea…",
                     "(we rank the first-token logit of the true concept among all 32 knob concepts)"))
    return "".join(out)


def main():
    t = ["# E5 prompts: exact wording, with the injections marked\n",
         "Generated by `scripts/e5_render.py` from the code's own strings, so this is word-for-word what Qwen3.8-27B "
         "sees. `…` marks text the model writes. ⚡ marks where the concept vector is being added to the "
         f"model's activations (layer {LAYER} of 64; level 10 = {DOSE} = 0.5 × the median residual norm at that layer, "
         "from the calibration made while the model writes under steering). The live logs in the web app should look like this.\n",
         "\n**Board.** Knobs 1–12 hold 10 concept vectors, 1 random direction and 1 sham (nothing), reshuffled per "
         "episode. The model never sees the concept list.\n",
         "\n**Thinking.** Each turn may think for up to 1,024 tokens. If it hits that limit, Qwen's own line is "
         f"inserted and it answers (still injected if the knob is on):\n\n> {e.THINK_CUT.split(chr(10) + '</think>')[0].strip()}\n",
         "\n**Reasoning effort.** Qwen3.8's system block carries its default `xhigh` effort line (first line below). Long thinking will often hit the 1,024-token cap; `--effort low` or `medium` would change that line.\n",
         "\n---\n\n## Rung A, **paste** arm (main run)\n", episode_md("explicit", True),
         "\n---\n\n## Rung A, **drop** arm (control)\n\nIdentical, except that no `For reference…` blocks appear: each user "
         "message is only its normal prompt.\n",
         "\n---\n\n## System prompts for the later rungs (everything else unchanged)\n",
         "\n**Rung B (inside):**\n" + block("SYSTEM", e.FRAMES["inside"].format(count="twelve", first=1, last=12)),
         "\n**Rung C (blind):**\n" + block("SYSTEM", e.FRAMES["blind"].format(count="twelve", first=1, last=12)),
         "\n---\n\n## Raw tool definitions (in the system block)\n", block("TOOLS", json.dumps(e.TOOLS, indent=1))]
    (ROOT / "docs" / "e5_prompts.md").write_text("".join(t))
    print("wrote docs/e5_prompts.md")


if __name__ == "__main__":
    main()
